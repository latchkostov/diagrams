import { mkdtempSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { classifyConflict, mergeEnglish, withoutGeneratedRegions } from "../../scripts/sync-lib";
import { invocation, sync, type Run } from "../../scripts/sync-runner";

const en = (entries: Record<string, string>) => `const en = ${JSON.stringify(entries)} as const;\nexport default en;\n`;

describe("sync conflict classification", () => {
  it("only regenerates explicit outputs, preserving handwritten docs, translations, sources and goldens", () => {
    expect(classifyConflict("skills/livediagrams/scripts/lib/app.mjs")).toBe("generated");
    expect(classifyConflict("skills/livediagrams/reference/format.md")).toBe("regions");
    expect(classifyConflict("src/i18n/en.ts")).toBe("english");
    expect(classifyConflict("tests/parity/goldens/node/skill.json")).toBe("golden");
    for (const file of [
      "skills/livediagrams/SKILL.md",
      "src/i18n/locales/de.json",
      "src/i18n/en/collab.ts",
      "deploy/self-host/README.md",
      ".claude-plugin/marketplace.json",
      "src/canvas/CanvasView.tsx",
    ])
      expect(classifyConflict(file)).toBe("manual");
  });

  it("strips generated regions alone, leaving authored skill prose for a normal three-way merge", () => {
    const text = "Authored\n<!-- BEGIN GENERATED fields -->\nold\n<!-- END GENERATED fields -->\nMore authored\n";
    expect(withoutGeneratedRegions(text)).toBe(
      "Authored\n<!-- BEGIN GENERATED fields -->\n\n<!-- regenerated by pnpm regen -->\n\n<!-- END GENERATED fields -->\nMore authored\n",
    );
  });
});

describe("English three-way union", () => {
  it("keeps both additions, matching edits, and deletions, preserving surrounding source", () => {
    const merged = mergeEnglish(
      en({ old: "Old", edit: "Before", remove: "Remove" }),
      en({ old: "Old", edit: "After", first: "First" }),
      en({ old: "Old", edit: "After", remove: "Remove", second: "Second" }),
    );
    expect(merged).toContain('"first":"First"');
    expect(merged).toContain('"second":"Second"');
    expect(merged).toContain('"edit":"After"');
    expect(merged).not.toContain('"remove"');
    expect(merged).toContain("export default en");
  });

  it("never picks a winner for conflicting translations or deletion versus edit", () => {
    expect(() => mergeEnglish(en({ same: "Base" }), en({ same: "Master" }), en({ same: "Branch" }))).toThrow(/same/);
    expect(() => mergeEnglish(en({ same: "Base" }), en({}), en({ same: "Branch" }))).toThrow(/same/);
    expect(() => mergeEnglish(en({}), en({ same: "Master" }), en({ same: "Branch" }))).toThrow(/same/);
    expect(() => mergeEnglish(en({}), 'const en = { "x": "a", "x": "b" }', en({}))).toThrow(/Duplicate/);
    expect(() => mergeEnglish(en({}), "const en = { ...other }", en({}))).toThrow(/string/);
    expect(() => mergeEnglish(en({}), "const en = {", en({}))).toThrow(/syntax/);
  });
});

describe("sync git orchestration", () => {
  it("uses a fixed Windows regeneration command and argv on macOS without interpolating shell arguments", () => {
    expect(invocation("pnpm", ["regen"], "darwin")).toEqual({ command: "pnpm", args: ["regen"] });
    expect(invocation("pnpm", ["regen"], "win32").args).toEqual(["/d", "/s", "/c", "pnpm regen"]);
    expect(() => invocation("pnpm", ["regen & other-command"], "win32")).toThrow(/fixed/);
    expect(invocation("git", ["show", ":2:path with spaces"], "win32")).toEqual({
      command: "git",
      args: ["show", ":2:path with spaces"],
    });
  });

  it("creates a signed regeneration commit when the rebased branch has no commits beyond master", async () => {
    const root = mkdtempSync(join(tmpdir(), "diagrams-sync-upstream-"));
    const calls: string[][] = [];
    try {
      const run: Run = (command, args) => {
        calls.push([command, ...args]);
        let stdout = "";
        if (command === "pnpm") writeFileSync(join(root, "vercel.json"), "fresh");
        else if (args[0] === "rev-parse") stdout = args[1] === "--git-path" ? ".git/inactive" : "upstream";
        else if (args[0] === "branch") stdout = "feature";
        else if (args[0] === "diff") stdout = "vercel.json";
        return { status: 0, stdout, stderr: "" };
      };
      await sync(root, run, () => {});
      expect(calls).toContainEqual(["git", "commit", "-S", "-m", "Regenerate derived artifacts after sync"]);
      expect(calls.some((call) => call.includes("--amend"))).toBe(false);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  it.each([false, true])(
    "regenerates before continuing (empty commit: %s), and signs final output changes",
    async (empty) => {
      const root = mkdtempSync(join(tmpdir(), "diagrams-fake-sync-"));
      const calls: string[][] = [];
      let rebasing = true;
      let conflict = true;
      let staged = false;
      let generations = 0;
      try {
        mkdirSync(join(root, ".git/rebase-merge"), { recursive: true });
        const run: Run = (command, args) => {
          calls.push([command, ...args]);
          let stdout = "";
          if (command === "pnpm") {
            generations++;
            writeFileSync(join(root, "vercel.json"), "fresh");
          } else if (args[0] === "rev-parse")
            stdout =
              args[1] === "--git-path"
                ? rebasing
                  ? ".git/rebase-merge"
                  : ".git/inactive"
                : args[1] === "HEAD"
                  ? "local"
                  : "upstream";
          else if (args[0] === "diff") {
            if (args.includes("--diff-filter=U")) stdout = conflict ? "vercel.json\0" : "";
            else stdout = staged ? "vercel.json\n" : "";
          } else if (args[0] === "show") stdout = "upstream";
          else if (args[0] === "add") {
            conflict = false;
            staged = !empty || generations > 1;
          } else if (args.includes("rebase")) {
            rebasing = false;
            staged = false;
            rmSync(join(root, ".git/rebase-merge"), { recursive: true });
          }
          return { status: 0, stdout, stderr: "" };
        };
        await sync(root, run, () => {}, true);
        expect(generations).toBe(2);
        expect(calls).toContainEqual(["git", "-c", "core.editor=true", "rebase", empty ? "--skip" : "--continue"]);
        expect(calls).toContainEqual(["git", "commit", "-S", "--amend", "--no-edit"]);
        expect(calls.some(([, action]) => action === "fetch")).toBe(false);
        expect(calls.filter(([, action]) => action === "add").every((call) => call.at(-1) === "vercel.json")).toBe(
          true,
        );
      } finally {
        rmSync(root, { recursive: true, force: true });
      }
    },
  );

  it("stops on a failed generator before continuing the rebase", async () => {
    const root = mkdtempSync(join(tmpdir(), "diagrams-failed-sync-"));
    const calls: string[][] = [];
    try {
      mkdirSync(join(root, ".git/rebase-merge"), { recursive: true });
      const run: Run = (command, args) => {
        calls.push([command, ...args]);
        return {
          status: command === "pnpm" ? 1 : 0,
          stdout: args[0] === "rev-parse" ? ".git/rebase-merge" : "",
          stderr: command === "pnpm" ? "generator failed" : "",
        };
      };
      await expect(sync(root, run, () => {}, true)).rejects.toThrow("generator failed");
      expect(calls.some(([, action]) => action === "commit" || action === "-c")).toBe(false);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  it("refuses dirty input before fetching or rebasing", async () => {
    const calls: string[][] = [];
    const run: Run = (_command, args) => {
      calls.push(args);
      return { status: 0, stdout: args[0] === "status" ? " M src/file.ts" : "no-rebase", stderr: "" };
    };
    await expect(sync(process.cwd(), run, () => {})).rejects.toThrow(/Commit or stash/);
    expect(calls.some((args) => args[0] === "fetch" || args[0] === "rebase")).toBe(false);
  });

  it("lists real and golden conflicts without running generators or staging them", async () => {
    const root = mkdtempSync(join(tmpdir(), "diagrams-fake-git-"));
    const calls: string[][] = [];
    let rebasing = false;
    try {
      const run: Run = (command, args) => {
        calls.push([command, ...args]);
        let stdout = "";
        if (args[0] === "rev-parse") stdout = rebasing ? ".git/rebase-merge" : ".git/not-rebasing";
        if (args[0] === "branch") stdout = "feature";
        if (args[0] === "rebase") {
          rebasing = true;
          mkdirSync(join(root, ".git/rebase-merge"), { recursive: true });
          return { status: 1, stdout: "conflict", stderr: "" };
        }
        if (args[0] === "diff") stdout = "src/real.ts\0tests/parity/goldens/node/example.json\0";
        return { status: 0, stdout, stderr: "" };
      };
      await expect(sync(root, run, () => {})).rejects.toThrow(/src\/real.ts[\s\S]*goldens[\s\S]*pnpm parity:update/);
      expect(calls).toContainEqual(["git", "fetch", "origin"]);
      expect(calls.some(([command, action]) => command === "pnpm" || action === "add")).toBe(false);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });
});
