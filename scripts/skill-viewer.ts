// The agent skill's offline Interactive HTML export (skills/livediagrams/scripts/export-html.mjs) runs on three
// files in scripts/lib/:
//   - inject.mjs: the app's injection (src/export/inject.ts) as plain JavaScript. Small and stable, so
//     `pnpm schemas` keeps it current and src/ai/skill/skill.test.ts fails when it's stale.
//   - viewer-template.html: the viewer (scripts/interactive-viewer.ts), one 1.2 MB minified page.
//   - icons.json: the SVG text of every icon the catalog uses.
// The template and the icons change with any canvas, live or export change, so they're refreshed only on
// release (`pnpm skill:release`, scripts/skill-release.mjs), never by `pnpm schemas` or a build: concurrent pull
// requests would otherwise conflict on an unmergeable file. The committed copy is what Claude Code's marketplace
// installs from git. The site's /skill/ folder and /livediagrams-skill.zip are built fresh from the current viewer
// (scripts/skill-assets.ts), so downloads are always current. `pnpm skill:check` reports a stale copy (nightly).

import { existsSync, readFileSync } from "node:fs";
import path from "node:path";
import { build } from "vite";
import { catalog } from "../src/stencils/catalog";
import { FALLBACK_ICON } from "../src/export/inject";

/** The released files, by path under skills/livediagrams/. */
export const RELEASED = {
  template: "scripts/lib/viewer-template.html",
  icons: "scripts/lib/icons.json",
} as const;
export const INJECT = "scripts/lib/inject.mjs";

/** One of the app's modules (`entry`, and what it imports) as one plain ES module, headed by `header` lines. */
export async function bundleModule(root: string, entry: string, header: string[]): Promise<string> {
  const out = await build({
    root,
    configFile: false,
    logLevel: "error",
    publicDir: false,
    build: {
      write: false,
      minify: false,
      copyPublicDir: false,
      reportCompressedSize: false,
      lib: { entry: path.join(root, entry), formats: ["es"], fileName: path.basename(entry, ".ts") },
    },
  });
  const outputs = (Array.isArray(out) ? out : [out]) as { output: { type: string; code?: string }[] }[];
  const chunk = outputs[0].output.find((o) => o.type === "chunk");
  if (!chunk?.code) throw new Error(`skill: bundling ${entry} produced no code.`);
  return `${header.map((line) => `// ${line}`).join("\n")}\n${chunk.code.replace(/\r\n/g, "\n")}`;
}

/** scripts/lib/inject.mjs. */
export const injectModule = (root: string) =>
  bundleModule(root, "src/export/inject.ts", [
    "Generated by `pnpm schemas` (scripts/skill-viewer.ts). Don't edit by hand.",
    "The app's Interactive HTML injection (src/export/inject.ts), so export-html.mjs makes the app's own file.",
  ]);

/**
 * The stencil icons the catalog uses (and the fallback box), name → SVG text: what export-html.mjs subsets from,
 * offline. The same text the app fetches from its own icon files, so both exports carry the same data URIs.
 */
export function iconMap(root: string): Record<string, string> {
  const dir = path.join(root, "src", "stencils", "icons");
  const names = new Set([FALLBACK_ICON, ...catalog.map((s) => s.icon)]);
  const out: Record<string, string> = {};
  for (const name of [...names].sort()) {
    const file = path.join(dir, `${name}.svg`);
    if (existsSync(file)) out[name] = readFileSync(file, "utf8").replace(/\r\n/g, "\n");
  }
  return out;
}

/** The released files as a fresh build makes them, given the current viewer template. */
export function releasedFiles(root: string, template: string): Record<string, string> {
  return {
    [RELEASED.template]: template,
    [RELEASED.icons]: JSON.stringify(iconMap(root)) + "\n",
  };
}

/** The plugin's version in `.claude-plugin/marketplace.json` text, bumped; the rest of the text is kept as is. */
export function bumpVersion(text: string, kind: "patch" | "minor"): { text: string; from: string; to: string } {
  const re = /("version":\s*")(\d+)\.(\d+)\.(\d+)(")/;
  const m = re.exec(text);
  if (!m) throw new Error('skill: .claude-plugin/marketplace.json has no "version": "x.y.z" to bump.');
  if (re.test(text.slice(m.index + m[0].length)))
    throw new Error("skill: .claude-plugin/marketplace.json has more than one version; bump it by hand.");
  const [major, minor, patch] = [Number(m[2]), Number(m[3]), Number(m[4])];
  const to = kind === "minor" ? `${major}.${minor + 1}.0` : `${major}.${minor}.${patch + 1}`;
  return {
    text: text.slice(0, m.index) + m[1] + to + m[5] + text.slice(m.index + m[0].length),
    from: `${major}.${minor}.${patch}`,
    to,
  };
}
