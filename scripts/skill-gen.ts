interface Example {
  slug: string;
  diagram: DiagramFile;
}

/** The public examples: *.json directly in src/examples/ (never the private/ folder). */
export function publicExamples(root: string): Example[] {
  const dir = path.join(root, "src", "examples");
  return readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isFile() && e.name.endsWith(".json"))
    .map((e) => e.name)
    .sort()
    .map((name) => ({
      slug: name.slice(0, -".json".length),
      diagram: JSON.parse(readFileSync(path.join(dir, name), "utf8")) as DiagramFile,
    }));
}

const props = (s: JsonSchema) => (s.properties ?? {}) as Record<string, JsonSchema>;

/** Data the skill's scripts check against (scripts/lib/spec.json). Limits come from the bundled app code. */
function spec() {
  return {
    $comment: NOTICE,
    format: DIAGRAM_FORMAT,
    site: SITE,
    shareWarnLength: SHARE_WARN_LENGTH,
    enums: {
      direction: ["LR", "TB"],
      tone: TONES,
      side: SIDES,
      edgeKind: ["async", "sync"],
      relation: [...EDGE_RELATIONS],
      annotationKind: [...ANNOTATION_KINDS],
      annotationShape: [...ANNOTATION_SHAPES],
      annotationColor: [...ANNOTATION_COLOR_IDS],
      textSize: [...ANNOTATION_TEXT_SIZES],
      status: ["up", "paused", "down"],
      metric: METRICS,
      op: ["<", "<=", "==", ">=", ">"],
      when: ["always", "eventually", "end", "at"],
    },
    nodeProps: props(nodeSimPropsSchema),
    edgeProps: props(edgeSimPropsSchema),
    stencils: catalog.map((s) => ({
      id: s.id,
      label: s.label,
      vendor: s.vendor,
      role: s.simRole,
      ...(BROKERS[baseStencilId(s.id)] ? { broker: BROKERS[baseStencilId(s.id)] } : {}),
      ...(STENCIL_ALIASES[s.id]?.length ? { aliases: [...STENCIL_ALIASES[s.id]] } : {}),
    })),
  };
}

const MOST_USED = 30;

/** reference/stencils.md: the most used stencils, then every stencil by vendor family. */
export function stencilsDoc(examples: Example[]): string {
  const uses = new Map<string, number>();
  for (const { diagram } of examples)
    for (const n of diagram.nodes) uses.set(n.stencil, (uses.get(n.stencil) ?? 0) + 1);
  const byId = new Map(catalog.map((s) => [s.id, s]));
  const line = (s: (typeof catalog)[number]) => {
    const id = s.id;
    const aka = (STENCIL_ALIASES[id] ?? []).slice(0, 4);
    return `- \`${id}\`: ${s.label} (${s.simRole})${aka.length ? `. Also: ${aka.join(", ")}` : ""}`;
  };
  const top = [...uses]
    .filter(([id]) => byId.has(id))
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .slice(0, MOST_USED)
    .map(([id]) => `\`${id}\``);
  const out = [
    "# Stencil cheat sheet",
    "",
    `<!-- ${NOTICE} -->`,
    "",
    `Every node's \`stencil\` is one of these ids (${catalog.length} in all; also at <${SITE}/schema/stencils.json>).`,
    "The role in brackets decides what the node does in live view: see [simulation.md](simulation.md).",
    "If nothing fits, use a `generic.*` stencil and say what it is in the label or sublabel.",
    "",
    "## Most used in the examples",
    "",
    top.join(", "),
  ];
  for (const family of FAMILIES) {
    const list = catalog.filter((s) => familyOf(s) === family.id);
    if (!list.length) continue;
    out.push("", `## ${family.label}`, "");
    const vendors = [...new Set(list.map((s) => s.vendor))];
    for (const v of vendors) for (const s of list.filter((x) => x.vendor === v)) out.push(line(s));
  }
  return out.join("\n") + "\n";
}

const range = (s: JsonSchema) => {
  if (Array.isArray(s.enum)) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
  if (Array.isArray(s.anyOf)) return "string or map";
  if (s.type === "array") return "string[]";
  const lo = typeof s.minimum === "number" ? s.minimum : undefined;
  const hi = typeof s.maximum === "number" ? s.maximum : undefined;
  return `${s.type}${lo !== undefined && hi !== undefined ? ` ${lo}..${hi}` : ""}`;
};

function propList(schema: JsonSchema, notes: Record<string, string>, where: string): string[] {
  return Object.entries(props(schema)).map(([key, s]) => {
    if (!notes[key]) throw new Error(`skill-gen: describe the ${where} property "${key}" in scripts/skill-gen.ts.`);
    return `- \`${key}\` (${range(s)}): ${notes[key]}`;
  });
}

/** Sections filled into the hand-written reference files between GENERATED markers. */
function regions(): Record<string, string> {
  const e = spec().enums;
  const code = (list: readonly string[]) => list.map((v) => `\`${v}\``).join(", ");
  return {
    enums: [
      `- Boundary \`tone\`: ${code(e.tone)}`,
      `- Edge \`kind\`: ${code(e.edgeKind)}; \`relation\`: ${code(e.relation)}; \`sourceSide\` / \`targetSide\`: ${code(e.side)}`,
      `- Annotation \`kind\`: ${code(e.annotationKind)}; \`shape\`: ${code(e.annotationShape)}; \`color\`: ${code(e.annotationColor)} or hex (\`#RGB\`, \`#RGBA\`, \`#RRGGBB\`, \`#RRGGBBAA\`; alpha is preserved); \`textSize\`: ${code(e.textSize)}`,
      `- Limits: ${LIMITS.maxNodes.toLocaleString("en-US")} nodes, ${LIMITS.maxEdges.toLocaleString("en-US")} edges, coordinates within ±${LIMITS.maxCoordinate.toLocaleString("en-US")}`,
    ].join("\n"),
    "node-props": propList(nodeSimPropsSchema, NODE_PROP_NOTES, "node").join("\n"),
    "edge-props": propList(edgeSimPropsSchema, EDGE_PROP_NOTES, "edge").join("\n"),
    "sim-limits": [
      `- Rates up to ${LIMITS.maxRatePerSec.toLocaleString("en-US")}/s, bursts and injections up to ${LIMITS.maxMessageCount.toLocaleString("en-US")} messages, times up to ${LIMITS.maxSimulationMs.toLocaleString("en-US")} ms.`,
      `- All traffic in the file together: at most ${LIMITS.maxTrafficVolume.toLocaleString("en-US")} messages as played (rate × duration, summed, ÷ each simulation's \`scale\`, the real messages per dot).`,
      `- Expectation metrics: ${code(e.metric)}, or \`{ "system": "inSystem" }\`; \`op\`: ${code(e.op)}; \`when\`: ${code(e.when)}.`,
    ].join("\n"),
  };
}

const REGION = /(<!-- BEGIN GENERATED ([\w-]+) -->\n)[\s\S]*?(<!-- END GENERATED \2 -->)/g;

/** Replaces every GENERATED region in `text`; unknown region names throw. */
export function fillRegions(text: string, file: string): string {
  const fill = regions();
  return text.replace(REGION, (_m, begin: string, name: string, end: string) => {
    if (!(name in fill)) throw new Error(`skill-gen: ${file} names an unknown generated region "${name}".`);
    return `${begin}\n${fill[name]}\n\n${end}`;
  });
}

/** Hand-written files with generated regions. */
export const REGION_FILES = ["reference/format.md", "reference/simulation.md"];

/** The app's validator and layout (src/ai/skill/app.ts and what it imports) as one plain ES module. */
export const bundleApp = (root: string) =>
  bundleModule(root, "src/ai/skill/app.ts", [
    NOTICE,
    "The app's own validator and layout (src/ai/skill/app.ts), bundled so the skill runs on plain Node.",
  ]);

/** Machine-read JSON: compact layout preserves every value while keeping the install ZIP within budget. */
export const specJson = (value: unknown): string => JSON.stringify(value) + "\n";

/** Every generated file, by path under skills/livediagrams/. */
export async function generateSkillFiles(root: string): Promise<Record<string, string>> {
  const files: Record<string, string> = {
    // Parsed by the scripts, not read: this layout stays legible and costs less of the download budget.
    "scripts/lib/spec.json": specJson(spec()),
    "scripts/lib/app.mjs": await bundleApp(root),
    // The HTML export's injection. Its template and icons are released, not generated here (scripts/skill-viewer.ts).
    [INJECT]: await injectModule(root),
    "reference/stencils.md": stencilsDoc(publicExamples(root)),
  };
  for (const rel of REGION_FILES) {
    const text = readFileSync(path.join(root, SKILL_DIR, rel), "utf8").replace(/\r\n/g, "\n");
    files[rel] = fillRegions(text, rel);
  }
  return files;
}
