import { AUTH_OPENER_POLICY, COMMON_HEADERS, EMBED_SCRIPT_HEADERS, OPENER_POLICY } from "./security-headers";
import { hostingBase, headersFile, selfHostCsp, selfHostFlatCsp, type SelfHostOptions } from "./self-host-headers";

export interface HostingOptions extends SelfHostOptions {
  base?: string;
}

export { hostingBase } from "./self-host-headers";

const json = (value: unknown) => `${JSON.stringify(value, null, 2)}\n`;
const pairs = (headers: Record<string, string>) => Object.entries(headers).map(([key, value]) => ({ key, value }));
const flatHeaders = (o: HostingOptions) => ({
  ...COMMON_HEADERS,
  "Content-Security-Policy": selfHostFlatCsp(o),
  "Cross-Origin-Opener-Policy": OPENER_POLICY,
  "Cache-Control": "no-cache",
});
const IMMUTABLE = "public, max-age=31536000, immutable";

/** Complete nginx http-context configuration, also used unchanged by the non-root Docker image. */
export function nginxServer(o: HostingOptions = {}): string {
  const base = hostingBase(o.base);
  const headers = {
    ...COMMON_HEADERS,
    "Content-Security-Policy": "$live_diagrams_csp",
    "Cross-Origin-Opener-Policy": "$live_diagrams_coop",
    "Cache-Control": "$live_diagrams_cache",
    "Access-Control-Allow-Origin": "$live_diagrams_cors",
    "Cross-Origin-Resource-Policy": "$live_diagrams_corp",
  };
  return `# Generated by pnpm headers:self-host; included inside nginx's http {}.
map $args $live_diagrams_csp {
    default "${selfHostCsp({ ...o, embed: false })}";
    "~(^|&)embed(=|&|$)" "${selfHostCsp({ ...o, embed: true })}";
}
map $uri $live_diagrams_coop {
    default "${OPENER_POLICY}";
    ~/auth\\.html$ "";
}
map "$status:$uri" $live_diagrams_cache {
    default "no-store";
    ~^(200|206|304):${base}assets/ "${IMMUTABLE}";
    ~^(200|206|304):.*/embed/[^/]+\\.js$ "${EMBED_SCRIPT_HEADERS["Cache-Control"]}";
    ~^(200|206|304): "no-cache";
}
map $uri $live_diagrams_cors {
    default "";
    ~/embed/[^/]+\\.js$ "${EMBED_SCRIPT_HEADERS["Access-Control-Allow-Origin"]}";
}
map $uri $live_diagrams_corp {
    default "";
    ~/embed/[^/]+\\.js$ "${EMBED_SCRIPT_HEADERS["Cross-Origin-Resource-Policy"]}";
}
server {
    listen 8080;
    server_name _;
    root /usr/share/nginx/html;
    index index.html;
    server_tokens off;
    absolute_redirect off;
    gzip on;
    gzip_vary on;
    gzip_types text/css application/javascript application/json image/svg+xml application/wasm;
${Object.entries(headers)
  .map(([k, v]) => `    add_header ${k} "${v}" always;`)
  .join("\n")}
    location = /healthz { access_log off; return 200 "ok\\n"; }
${base === "/" ? "" : `    location = ${base.slice(0, -1)} { return 308 ${base}$is_args$args; }\n`}
    location ${base}assets/ { try_files $uri =404; }
    location ~ /embed/[^/]+\\.js$ { try_files $uri =404; }
    location ${base} { try_files $uri $uri/ ${base}index.html; }
${base === "/" ? "" : "    location / { return 404; }\n"}}
`;
}

export function caddyServer(o: HostingOptions = {}): string {
  const base = hostingBase(o.base);
  const lines = (h: Record<string, string>) =>
    Object.entries(h)
      .map(([k, v]) => `            ${k} "${v}"`)
      .join("\n");
  return `# Generated by pnpm headers:self-host. Change :8080 to your domain for automatic HTTPS.
:8080 {
    encode zstd gzip
    route {
        @embed expression \`{http.request.uri.query}.matches('(^|&)embed(=|&|$)')\`
        @notAuth not path */auth.html
        @assets path ${base}assets/*
        @script path ${base}embed/*.js
        header {
${lines({ ...COMMON_HEADERS, "Content-Security-Policy": selfHostCsp({ ...o, embed: false }), "Cache-Control": "no-cache" })}
        }
        header @embed Content-Security-Policy "${selfHostCsp({ ...o, embed: true })}"
        header @notAuth Cross-Origin-Opener-Policy "${OPENER_POLICY}"
        header @assets {
            Cache-Control "${IMMUTABLE}"
            match status 200 206 304
        }
        header @script {
${lines(Object.fromEntries(Object.entries(EMBED_SCRIPT_HEADERS).filter(([k]) => k !== "Cache-Control")))}
        }
        header @script {
            Cache-Control "${EMBED_SCRIPT_HEADERS["Cache-Control"]}"
            match status 200 206 304
        }
${base === "/" ? "" : `        redir ${base.slice(0, -1)} ${base}?{http.request.uri.query} 308\n`}
        ${base === "/" ? "handle" : `handle_path ${base}*`} {
            root * /srv/live-diagrams
            @static path /assets/* /embed/*
            handle @static {
                file_server
            }
            handle {
                try_files {path} {path}/ /index.html
                file_server
            }
        }
    }
}
`;
}

/** All target files derive their header values from security-headers.ts via selfHostCsp. */
export function hostingTemplates(o: HostingOptions = {}): Record<string, string> {
  const base = hostingBase(o.base);
  const flat = flatHeaders(o);
  const blocks = headersFile(o);
  const query = [{ type: "query", key: "embed" }];
  const vercel = {
    $schema: "https://openapi.vercel.sh/vercel.json",
    headers: [
      { source: "/(.*)", headers: pairs({ ...COMMON_HEADERS, "Cache-Control": "no-cache" }) },
      {
        source: "/(.*)",
        missing: query,
        headers: pairs({ "Content-Security-Policy": selfHostCsp({ ...o, embed: false }) }),
      },
      {
        source: "/(.*)",
        has: query,
        headers: pairs({ "Content-Security-Policy": selfHostCsp({ ...o, embed: true }) }),
      },
      { source: "/((?!.*auth\\.html$).*)", headers: pairs({ "Cross-Origin-Opener-Policy": OPENER_POLICY }) },
      { source: `${base}assets/(.*)`, headers: pairs({ "Cache-Control": IMMUTABLE }) },
      { source: `${base}embed/([^/]+\\.js)`, headers: pairs(EMBED_SCRIPT_HEADERS) },
    ],
    rewrites: [{ source: `${base}((?!assets/|embed/).*)`, destination: `${base}index.html` }],
  };
  const tomlBlock = (pattern: string, h: Record<string, string>) =>
    `[[headers]]\nfor = ${JSON.stringify(pattern)}\n[headers.values]\n${Object.entries(h)
      .map(([k, v]) => `${JSON.stringify(k)} = ${JSON.stringify(v)}`)
      .join("\n")}\n`;
  const policy = (name: string, h: Record<string, string>) =>
    json({
      Name: name,
      Comment: "Generated by pnpm headers:self-host",
      CustomHeadersConfig: {
        Quantity: Object.keys(h).length,
        Items: Object.entries(h).map(([Header, Value]) => ({ Header, Value, Override: true })),
      },
    });
  // frame-ancestors is ignored in a meta policy: GitHub Pages cannot enforce an embed allowlist.
  const meta = flat["Content-Security-Policy"].replace(/; frame-ancestors [^;]+/, "");
  return {
    "docker/default.conf": nginxServer(o),
    "nginx/nginx.conf": nginxServer(o),
    "caddy/Caddyfile": caddyServer(o),
    "netlify/netlify.toml": `[build]\ncommand = "pnpm build:internal"\npublish = "dist"\n\n${tomlBlock(`${base}*`, Object.fromEntries(Object.entries(flat).filter(([k]) => k !== "Cache-Control")))}\n${tomlBlock(base, { "Cache-Control": "no-cache" })}\n${tomlBlock(`${base}index.html`, { "Cache-Control": "no-cache" })}\n${tomlBlock(`${base}assets/*`, { "Cache-Control": IMMUTABLE })}\n${tomlBlock(`${base}embed/*.js`, EMBED_SCRIPT_HEADERS)}\n${tomlBlock(`${base}auth.html`, { "Cross-Origin-Opener-Policy": AUTH_OPENER_POLICY })}\n[[redirects]]\nfrom = "${base}*"\nto = "${base}index.html"\nstatus = 200\n`,
    "vercel/vercel.json": json(vercel),
    "cloudflare/_headers": `${blocks}${base}assets/*\n  Cache-Control: ${IMMUTABLE}\n${base}\n  Cache-Control: no-cache\n${base}index.html\n  Cache-Control: no-cache\n${base}auth.html\n  ! Cross-Origin-Opener-Policy\n`,
    "cloudflare/_redirects":
      "# Use Pages native SPA fallback (no top-level 404.html).\n# Proxy catch-alls override existing assets and must not be added here.\n",
    "github-pages/meta-csp.html": `<meta http-equiv="Content-Security-Policy" content="${meta.replaceAll('"', "&quot;")}">\n`,
    "azure/staticwebapp.config.json": json({
      globalHeaders: flat,
      routes: [
        { route: `${base}assets/*`, headers: { "Cache-Control": IMMUTABLE } },
        { route: `${base}embed/*.js`, headers: EMBED_SCRIPT_HEADERS },
        { route: `${base}auth.html`, headers: { "Cross-Origin-Opener-Policy": "" } },
      ],
      navigationFallback: { rewrite: `${base}index.html`, exclude: [`${base}assets/*`, `${base}embed/*`] },
    }),
    "aws/response-headers-policy.json": policy("live-diagrams", flat),
    "aws/embed-response-headers-policy.json": policy("live-diagrams-embed-script", {
      ...flat,
      ...EMBED_SCRIPT_HEADERS,
    }),
    "aws/assets-response-headers-policy.json": policy("live-diagrams-assets", { ...flat, "Cache-Control": IMMUTABLE }),
    "aws/auth-response-headers-policy.json": policy(
      "live-diagrams-auth",
      Object.fromEntries(Object.entries(flat).filter(([k]) => k !== "Cross-Origin-Opener-Policy")),
    ),
  };
}
