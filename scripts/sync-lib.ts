import ts from "typescript";
export type GeneratedPolicy = { files: string[]; regions: string[] };

export function classifyConflict(
  file: string,
  generated: GeneratedPolicy,
): "golden" | "generated" | "regions" | "english" | "manual" {
  if (file.startsWith("tests/parity/goldens/")) return "golden";
  if (generated.files.includes(file)) return "generated";
  if (generated.regions.includes(file)) return "regions";
  if (file === "src/i18n/en.ts") return "english";
  return "manual";
}

export function withoutGeneratedRegions(text: string): string {
  return text
    .replaceAll("\r\n", "\n")
    .replace(
      /(<!-- BEGIN GENERATED ([\w-]+) -->\n)[\s\S]*?(<!-- END GENERATED \2 -->)/g,
      "$1\n<!-- regenerated by pnpm regen -->\n\n$3",
    );
}

/** Parse data, never execute either side of a conflicted catalog. Reject syntax we cannot merge safely. */
function catalog(text: string) {
  const file = ts.createSourceFile("en.ts", text, ts.ScriptTarget.Latest, true);
  if ((file as ts.SourceFile & { parseDiagnostics: unknown[] }).parseDiagnostics.length)
    throw new Error("English catalog has syntax errors");
  let object: ts.ObjectLiteralExpression | undefined;
  for (const statement of file.statements) {
    if (!ts.isVariableStatement(statement)) continue;
    for (const declaration of statement.declarationList.declarations) {
      if (!ts.isIdentifier(declaration.name) || declaration.name.text !== "en") continue;
      let value = declaration.initializer;
      if (value && ts.isAsExpression(value)) value = value.expression;
      if (value && ts.isObjectLiteralExpression(value)) object = value;
    }
  }
  if (!object) throw new Error("Expected const en = { ... } as const");
  const entries = new Map<string, { value: string; source: string }>();
  for (const property of object.properties) {
    if (
      !ts.isPropertyAssignment(property) ||
      !ts.isStringLiteral(property.name) ||
      !ts.isStringLiteral(property.initializer)
    )
      throw new Error("English catalog merge supports string keys and string values only");
    const key = property.name.text;
    if (entries.has(key)) throw new Error(`Duplicate English key: ${key}`);
    entries.set(key, { value: property.initializer.text, source: property.getFullText(file).trim() });
  }
  return { entries, prefix: text.slice(0, object.getStart(file) + 1), suffix: text.slice(object.end - 1) };
}

/** Three-way union: additions, deletions and identical edits are safe; competing edits stay conflicts. */
export function mergeEnglish(baseText: string, upstreamText: string, branchText: string): string {
  const base = catalog(baseText);
  const upstream = catalog(upstreamText);
  const branch = catalog(branchText);
  // Also preserve edits to surrounding source rather than silently dropping them.
  const surrounding = (field: "prefix" | "suffix") => {
    if (upstream[field] === branch[field] || branch[field] === base[field]) return upstream[field];
    if (upstream[field] === base[field]) return branch[field];
    throw new Error(`Competing English catalog ${field} edits`);
  };
  const result: string[] = [];
  const keys = new Set([...upstream.entries.keys(), ...branch.entries.keys(), ...base.entries.keys()]);
  for (const key of keys) {
    const before = base.entries.get(key);
    const left = upstream.entries.get(key);
    const right = branch.entries.get(key);
    let chosen;
    if (left?.value === right?.value || right?.value === before?.value) chosen = left;
    else if (left?.value === before?.value) chosen = right;
    else throw new Error(`Competing English key: ${key}`);
    if (chosen) result.push(`${chosen.source},`);
  }
  return `${surrounding("prefix")}\n${result.join("\n")}\n${surrounding("suffix")}`;
}
