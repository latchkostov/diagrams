import type { Plugin } from "vite";
import { COMMON_HEADERS, cspDirectives, OPENER_POLICY } from "./security-headers";

/**
 * Security headers for a self-hosted copy (docs/SELF-HOSTING.md), from the same policy the public site sends
 * (./security-headers.ts), in the formats common static hosts read: an nginx snippet and a `_headers` file
 * (Netlify, Cloudflare Pages and others). `pnpm schemas` writes the samples in deploy/self-host/ (a unit test
 * fails when they're stale); `pnpm headers:self-host` writes them for your own domains.
 *
 * What differs from the public site:
 *  - No outside origins. A self-hosted copy built without the cloud providers' variables never calls Google,
 *    Microsoft or Dropbox, so their script, connect and frame sources go (`providers: true` keeps them).
 *  - frame-ancestors: the app, and its read-only embeds, may be framed by this site and the domains you list
 *    (an intranet, a wiki), never by any site. With no list, by this site only.
 */

export interface SelfHostOptions {
  /** Origins that may frame embeds (`?embed=1`), e.g. `https://wiki.example.com`, `https://*.example.com`. */
  frameAncestors?: string[];
  /** Keep the storage providers' origins (a copy built with VITE_GOOGLE_*, VITE_ONEDRIVE_* or VITE_DROPBOX_*). */
  providers?: boolean;
}

/** An origin a CSP source list accepts: https, a host (optionally `*.`), an optional port; nothing else. */
const ORIGIN = /^https:\/\/(\*\.)?[a-z0-9-]+(\.[a-z0-9-]+)*(:\d{1,5})?$/i;

/** Checks the frame-ancestors list: origins only, so nothing else can slip into the policy. */
export function frameAncestorList(list: readonly string[] = []): string[] {
  const out = list.map((s) => s.trim().replace(/\/+$/, "")).filter(Boolean);
  const bad = out.filter((s) => !ORIGIN.test(s));
  if (bad.length)
    throw new Error(
      `frame-ancestors takes https origins such as https://wiki.example.com or https://*.example.com, not: ${bad.join(", ")}`,
    );
  return [...new Set(out)];
}

/** The policy for the app (`embed: false`) or an embed, for a self-hosted copy. */
export function selfHostCsp(o: SelfHostOptions & { embed: boolean }): string {
  const ancestors = frameAncestorList(o.frameAncestors);
  return cspDirectives({ embed: o.embed })
    .map(([name, values]): [string, string[]] => {
      if (name === "frame-ancestors") return [name, ["'self'", ...(o.embed ? ancestors : [])]];
      // Keep keywords and schemes ('self', data:, blob:, 'unsafe-inline'); outside origins only with providers.
      return [name, o.providers ? values : values.filter((v) => !/^https?:/.test(v))];
    })
    .map(([name, values]) => `${name} ${values.join(" ")}`)
    .join("; ");
}

const banner = (comment: string, o: SelfHostOptions) => {
  const ancestors = frameAncestorList(o.frameAncestors);
  return [
    `${comment} Live Diagrams: security headers for a self-hosted copy (docs/SELF-HOSTING.md).`,
    `${comment} Generated by scripts/self-host-headers.ts (\`pnpm headers:self-host\`); regenerate rather than edit.`,
    `${comment} Embeds may be framed by: ${ancestors.length ? `this site, ${ancestors.join(", ")}` : "this site only"}.`,
    ...(o.providers ? [] : [`${comment} No outside origins: build without the cloud storage variables.`]),
  ].join("\n");
};

/**
 * nginx: a `map` (in the `http {}` block) picks the embed policy for any URL with an `embed` parameter, as the
 * app does; the `add_header` lines go in the `server {}` block. nginx drops inherited `add_header`s in a block
 * that sets its own, so a `location` with any `add_header` needs these lines too.
 */
export function nginxHeaders(o: SelfHostOptions = {}): string {
  const header = (name: string, value: string) => `    add_header ${name} "${value}" always;`;
  return `${banner("#", o)}

# 1. In the http {} block: the embed policy for any URL with an "embed" parameter (?embed=1), as the app reads it.
map $args $live_diagrams_csp {
    default "${selfHostCsp({ ...o, embed: false })}";
    "~(^|&)embed(=|&|$)" "${selfHostCsp({ ...o, embed: true })}";
}

# 2. In the server {} block that serves the build (dist/). Repeat these lines in any location {} that has its
#    own add_header: nginx drops the inherited ones there.
server {
    # listen, server_name, TLS and your sign-in (auth_request, oauth2-proxy...) as usual.
    root /srv/live-diagrams;
    index index.html;

    add_header Content-Security-Policy $live_diagrams_csp always;
${Object.entries(COMMON_HEADERS)
  .map(([k, v]) => header(k, v))
  .join("\n")}
    add_header Cross-Origin-Opener-Policy "${OPENER_POLICY}" always;
}
`;
}

/**
 * A `_headers` file (Netlify, Cloudflare Pages): one policy for every path, since these files can't tell an
 * embed by its query. With a frame-ancestors list it's the embed policy (the app may then be framed by those
 * domains too); without one, the app's (nothing outside this site frames it). Copy it into dist/ before
 * deploying.
 */
export function headersFile(o: SelfHostOptions = {}): string {
  const embed = frameAncestorList(o.frameAncestors).length > 0;
  const lines = {
    "Content-Security-Policy": selfHostCsp({ ...o, embed }),
    ...COMMON_HEADERS,
    "Cross-Origin-Opener-Policy": OPENER_POLICY,
  };
  return `${banner("#", o)}
/*
${Object.entries(lines)
  .map(([k, v]) => `  ${k}: ${v}`)
  .join("\n")}
`;
}

/** The example list the "framed" samples use. */
export const EXAMPLE_FRAME_ANCESTORS = ["https://intranet.example.com", "https://*.example.com"];

/** deploy/self-host/: the samples, by path. */
export function selfHostSamples(): Record<string, string> {
  return {
    "nginx.conf": nginxHeaders(),
    _headers: headersFile(),
    "framed/nginx.conf": nginxHeaders({ frameAncestors: EXAMPLE_FRAME_ANCESTORS }),
    "framed/_headers": headersFile({ frameAncestors: EXAMPLE_FRAME_ANCESTORS }),
  };
}

/** The headers for one request to a self-hosted copy, as the nginx sample sends them. */
export function selfHostHeadersFor(url: string, o: SelfHostOptions = {}): Record<string, string> {
  const u = new URL(url, "http://localhost");
  return {
    ...COMMON_HEADERS,
    "Content-Security-Policy": selfHostCsp({ ...o, embed: new URLSearchParams(u.search).has("embed") }),
    ...(/\/auth\.html$/.test(u.pathname) ? {} : { "Cross-Origin-Opener-Policy": OPENER_POLICY }),
  };
}

/**
 * `vite preview` with a self-hosted copy's headers instead of the public site's, when PREVIEW_HEADERS=self-host
 * (the e2e suite's self-hosting projects). Runs after ./security-headers.ts's plugin, so its headers win.
 */
export function selfHostPreviewHeaders(): Plugin {
  return {
    name: "self-host-preview-headers",
    configurePreviewServer(server) {
      if (process.env.PREVIEW_HEADERS !== "self-host") return;
      server.middlewares.use((req, res, next) => {
        for (const [k, v] of Object.entries(selfHostHeadersFor(req.originalUrl ?? req.url ?? "/"))) res.setHeader(k, v);
        next();
      });
    },
  };
}
